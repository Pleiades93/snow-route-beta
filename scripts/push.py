def _limits_changed_lines(old_text, new_text):
    old = [] if old_text is None else old_text.splitlines()
    new = new_text.splitlines()
    added, deletions = set(), set()
    # autojunk off: unchanged repetitive lines are not additions.
    sm = difflib.SequenceMatcher(None, old, new, autojunk=False)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag in ("insert", "replace"):
            added.update(range(j1, j2))
        elif tag == "delete":
            deletions.add((j1, i1, i2))
    return added, deletions


def _as_text(data):
    """bytes -> str, or None when the content is not text (a NUL
    in the first chunk - git's own binary heuristic)."""
    if data is None:
        return None
    if b"\x00" in data[:8000]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def _limits_verdict(mod, changed, labels):
    """changed: [(path, old_bytes, new_bytes)] - None means the
    file does not exist on that side. The decisions are
    check-pr-limits.py's own shared functions; this gate only
    feeds them the push's diff (one push is one commit, so the
    size rule is judged per push). Binary files carry no added
    lines, exactly as git's diff reports them. CI stays the
    authority on the real labels; --labels declares them for
    this local pre-check only."""
    errors = []
    product = 0
    for path, old_bytes, new_bytes in changed:
        old_text = _as_text(old_bytes)
        new_text = _as_text(new_bytes)
        binary = (old_bytes is not None and old_text is None) or \
            (new_bytes is not None and new_text is None)
        if old_bytes is None and new_bytes is not None:
            err = mod.root_file_error(path)
            if err:
                errors.append(err)
        if binary or new_bytes is None:
            continue
        added, deletions = _limits_changed_lines(old_text, new_text)
        if mod.is_product_path(path):
            product += len(added)
        errors.extend(mod.changed_line_errors(path, old_text, new_text, added, deletions))
    err = mod.size_error("this push", product, labels)
    if err:
        errors.append(err)
    return errors, product


def limits_gate_plan(root, resolved, labels):
    """Plan mode judges the working tree against the local git
    HEAD - never the network. No git HEAD: say so, never silent."""
    mod = _limits_module(root)
    if mod is None:
        print("LIMITS GATE SKIPPED: scripts/check-pr-limits.py is not "
              "in this tree (it predates the gate)")
        return None
    probe = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                           capture_output=True, text=True)
    if probe.returncode != 0:
        print("LIMITS GATE SKIPPED (plan): no local git HEAD to "
              "diff against")
        return None
    changed = []
    for p in resolved:
        new_bytes = (root / p).read_bytes() \
            if (root / p).is_file() else None
        got = subprocess.run(["git", "-C", str(root), "show", f"HEAD:{p}"],
                             capture_output=True)
        old_bytes = got.stdout if got.returncode == 0 else None
        if old_bytes != new_bytes:
            changed.append((p, old_bytes, new_bytes))
    errors, product = _limits_verdict(mod, changed, labels)
    if errors:
        return "the PR limits fail locally: " + "; ".join(errors)
    print(f"LIMITS GATE: {len(changed)} changed file(s) within the PR "
          f"limits ({product} product line(s) of {mod.SIZE_LIMIT})")
    return None


def limits_gate_push(root, gh, branch, resolved, labels):
    """Push mode judges against the branch's own blobs - the
    exact diff this push will create."""
    import base64
    mod = _limits_module(root)
    if mod is None:
        print("LIMITS GATE SKIPPED: scripts/check-pr-limits.py is not "
              "in this tree (it predates the gate)")
        return None
    _, remote = remote_blobs(gh, branch)
    local = local_blob_map(root)
    changed = []
    base = f"/repos/Pleiades93/{REPO_SLUG}"
    for p in resolved:
        if remote.get(p) == local.get(p):
            continue
        new_bytes = (root / p).read_bytes() \
            if (root / p).is_file() else None
        old_bytes = None
        if p in remote:
            blob = gh.api("GET", f"{base}/git/blobs/{remote[p]}")
            old_bytes = base64.b64decode(blob["content"])
        changed.append((p, old_bytes, new_bytes))
    errors, product = _limits_verdict(mod, changed, labels)
    if errors:
        return "the PR limits fail locally: " + "; ".join(errors)
    print(f"LIMITS GATE: {len(changed)} changed file(s) within the PR "
          f"limits ({product} product line(s) of {mod.SIZE_LIMIT})")
    return None


def mirrors_gate(prospective_root, instrument_root):
    """The push tree's hand-maintained mirrors must agree with
    their sources (class C4 generalized; scripts/check-mirrors.py
    owns the family set and the comparisons). Mirrors are
    tree-wide facts, not change-scoped ones, so the whole set is
    verified against the PROSPECTIVE tree on every push - a drift
    that predates the round still refuses the push that would
    carry it past the gate unexamined, and the round that moves a
    source must move its mirror in the same push. The checking
    logic loads from the LOCAL tree - the measuring instrument,
    exempt from the prospective overlay like build-pages.py.
    Returns an error string or None."""
    script = instrument_root / "scripts" / "check-mirrors.py"
    if not script.is_file():
        print("MIRRORS GATE SKIPPED: scripts/check-mirrors.py is not in "
              "this tree (it predates the gate)")
        return None
    spec = importlib.util.spec_from_file_location("snow_check_mirrors", script)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.gate(prospective_root)


def registry_targets(root, probe, goal_dir):
    """The files a grep probe pins. Registered absolute paths name
    the shared repo (…/beta1/repo/…); the part after that prefix is
    the repo-relative path, remapped onto the push root. Any other
    absolute path is used as-is (a probe may pin a file outside the
    repo). A relative path resolves against the registry's goal
    directory, exactly as the shared runner resolves it - those
    probes pin goal documents, not repo files."""
    raw = probe.get("file") or probe.get("file_glob")
    if not raw:
        return []
    if os.path.isabs(raw):
        marker = "/beta1/repo/"
        cand = root / raw.split(marker, 1)[1] if marker in raw else Path(raw)
    else:
        cand = goal_dir / raw
    if probe.get("file_glob"):
        return [Path(f) for f in sorted(globmod.glob(str(cand)))]
    return [cand]


def registry_gate(root, label="push"):
    """The registry's grep probes must pass against the push tree.
    Returns an error string or None. Mirrors the shared runner's
    semantics (~/workspace/tools/fix-checks/run_fix_checks.py): a
    missing target is a failure for both grep types, never a pass;
    ci_only probes are not this shell's to run. Failures listed in
    the registry's standing-failures manifest are the recorded
    baseline and are reported, not blocking."""
    path = os.environ.get("SNOW_FIX_CHECKS_REGISTRY", REGISTRY_DEFAULT)
    if not os.path.isfile(path):
        if "SNOW_FIX_CHECKS_REGISTRY" in os.environ:
            return ("SNOW_FIX_CHECKS_REGISTRY names a registry that does not "
                    f"exist: {path} - a named gate that cannot run refuses")
        print(f"REGISTRY GATE SKIPPED: no registry at {path} "
              "(this environment carries none)")
        return None
    import json
    checks = json.loads(Path(path).read_text())["checks"]
    goal_dir = Path(path).resolve().parent.parent
    baseline = set()
    standing = Path(path).with_name("fix-checks-standing-failures.json")
    if standing.is_file():
        entries = json.loads(standing.read_text()).get("standing_failures", [])
        baseline = {e if isinstance(e, str) else e.get("id") for e in entries}
    fails, based, ran = [], [], 0
    for probe in checks:
        if probe.get("type") not in ("grep_present", "grep_absent"):
            continue
        if probe.get("ci_only"):
            continue
        ran += 1
        targets = registry_targets(root, probe, goal_dir)
        found = False
        missing = not targets
        for t in targets:
            try:
                content = t.read_text(errors="ignore")
            except OSError:
                missing = True
                continue
            if probe["pattern"] in content:
                found = True
        ok = (found if probe["type"] == "grep_present" else not found) and not missing
        if not ok:
            (based if probe["id"] in baseline else fails).append(probe["id"])
    if fails:
        return ("the fix-checks registry fails against this tree: "
                + ", ".join(fails)
                + " - a round whose code motion orphans a probe literal "
                "re-pins it in the same round (the C1 class; six stale "
                "patterns reached the 1.258 close-out unrun). Fix the "
                "app if the probe is right, or re-pin the probe in the "
                "registry if the code legitimately moved")
    note = f" ({len(based)} standing-baseline failure(s) tolerated: {', '.join(based)})" if based else ""
    print(f"REGISTRY GATE: {ran} grep probes run serially against the {label} tree, "
          f"no unaccounted failures{note}")
    return None


def registry_sync_gate(prospective_root, instrument_root):
    """The vendored registry pair in the tree must equal what the
    canonical registry generates (issue #178; scripts/
    sync-fix-checks.py owns the subset rule and the generation).
    The checking logic loads from the LOCAL tree - the measuring
    instrument, exempt from the prospective overlay like the other
    gates - while the vendored files are read from the tree being
    certified, so a stale or hand-edited vendored copy that would
    land with this push cannot certify it. A tree carrying no
    vendored pair predates the vendoring and skips with a printed
    line. Returns an error string or None."""
    script = instrument_root / "scripts" / "sync-fix-checks.py"
    if not script.is_file():
        print("REGISTRY SYNC GATE SKIPPED: scripts/sync-fix-checks.py "
              "is not in this tree (it predates the gate)")
        return None
    spec = importlib.util.spec_from_file_location("snow_sync_fix_checks", script)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.check_gate(prospective_root)


def do_push(root, branch, message, resolved, labels=()):
    err = registry_gate(root)
    if err:
        return fail(err)
    err = registry_sync_gate(root, root)
    if err:
        return fail(err)
    gh, helper = helper_module()
    err = preflight_prospective(root, gh, branch, resolved)
    if err:
        return fail(err)
    err = limits_gate_push(root, gh, branch, resolved, labels)
    if err:
        return fail(err)
    pairs = [f"{p}={p}" for p in resolved]
    cmd = [sys.executable, helper, "--repo", REPO_SLUG, "--branch", branch,
           "push", "--message", message] + pairs
    # cwd=root (Codex P2 on PR #146): the pairs are repo-relative, so
    # the transport must read them from the VALIDATED tree, not from
    # whatever directory the caller happened to invoke this from.
    proc = subprocess.run(cmd, cwd=root, capture_output=True, text=True, timeout=600)
    sys.stdout.write(proc.stdout)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        return fail("the transport push failed (see above) - nothing was verified")
    # Verify the PUSHED tree: every pushed path's remote blob must
    # equal the local file's blob at the branch's new head.
    head, remote = remote_blobs(gh, branch)
    bad = [p for p in resolved if remote.get(p) != blob_sha(root / p)]
    if bad:
        return fail("pushed-tree verification failed - the remote blob differs from the "
                    "local file for: " + ", ".join(bad))
    print(f"PUSH VERIFIED: {len(resolved)} file(s) on {branch} @ {head[:8]} - "
          "every remote blob equals its local file")
    return 0


