def preflight_prospective(root, gh, branch, resolved):
    """The tree this push would CREATE must itself build. Returns an
    error string or None. Runs for EVERY push (Codex P2 on PR #146:
    an input-only push - CHANGELOG.md alone, artwork alone - named
    neither parts/ nor a derived artifact and skipped every check,
    stranding stale derived files on the branch). Only inputs that
    differ from the branch and are NOT in the set can make the
    prospective tree differ from the local one; those are overlaid
    with their branch blobs in a temp copy and build-pages --check
    is run there. When nothing differs outside the set, the
    prospective tree IS the local tree and the check runs on it."""
    _, remote = remote_blobs(gh, branch)
    local = local_blob_map(root)
    # The prospective tree is the branch's tree plus this set. Three
    # kinds of local content do not reach it unchanged: files whose
    # branch blob differs (overlay the branch version), files the
    # branch has that the local tree lacks (restore the branch
    # version), and local-only files outside the set (drop them).
    # The checker itself is exempt from overlay/drop: it is the
    # measuring instrument, not a measured input (and a prospective
    # copy without it could not be checked at all). The exemption
    # covers the checker's whole import closure (issue #180): the
    # temp copy's build-pages.py imports csp_stamp, assemble and
    # release from its own directory, and release loads
    # source_query by path - exempting only the entry point left
    # those four branch-sourced and locally EXECUTED whenever they
    # differed outside the push set. Instruments run from trusted
    # local code; the prospective tree is their data.
    instruments = {"scripts/build-pages.py", "scripts/csp_stamp.py",
                   "scripts/assemble.py", "scripts/release.py",
                   "scripts/source_query.py"}
    overlay = sorted(p for p in remote
                     if p not in resolved and p not in instruments and remote[p] != local.get(p))
    drop = sorted(p for p in local
                  if p not in resolved and p not in instruments and p not in remote)
    if not overlay and not drop:
        proc = subprocess.run([sys.executable, str(root / "scripts" / "build-pages.py"), "--check"],
                              cwd=root, capture_output=True, text=True, timeout=300)
        if proc.returncode != 0:
            tail = (proc.stdout + proc.stderr).strip().splitlines()
            return ("the tree this push would create is the local tree, and it does not "
                    "build - build-pages --check said: " + (tail[-1] if tail else "(no output)"))
        err = receipts_gate(root, root, remote, local, resolved)
        if err:
            return "the prospective remote tree fails the receipts gate: " + err
        err = census_gate(root, root, remote, local, resolved)
        if err:
            return "the prospective remote tree fails the census gate: " + err
        err = mirrors_gate(root, root)
        if err:
            return "the prospective remote tree fails the mirrors gate: " + err
        err = survivors_gate(root, root, remote, local, resolved)
        if err:
            return "the prospective remote tree fails the survivors gate: " + err
        return parts_scan_gate(root, root)
    import base64
    import shutil
    import tempfile
    tmp = Path(tempfile.mkdtemp(prefix="push-prospective-"))
    try:
        shutil.copytree(root, tmp, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns(".git", "node_modules", "__pycache__"))
        base = f"/repos/Pleiades93/{REPO_SLUG}"
        for rel in overlay:
            blob = gh.api("GET", f"{base}/git/blobs/{remote[rel]}")
            data = base64.b64decode(blob["content"])
            dest = tmp / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        for rel in drop:
            (tmp / rel).unlink(missing_ok=True)
        err = registry_gate(tmp, label="prospective")
        if err:
            return ("the prospective remote tree fails the registry gate: " + err)
        err = registry_sync_gate(tmp, root)
        if err:
            return ("the prospective remote tree fails the registry sync gate: " + err)
        err = receipts_gate(tmp, root, remote, local, resolved)
        if err:
            return ("the prospective remote tree fails the receipts gate: " + err)
        err = census_gate(tmp, root, remote, local, resolved)
        if err:
            return ("the prospective remote tree fails the census gate: " + err)
        err = mirrors_gate(tmp, root)
        if err:
            return ("the prospective remote tree fails the mirrors gate: " + err)
        err = survivors_gate(tmp, root, remote, local, resolved)
        if err:
            return "the prospective remote tree fails the survivors gate: " + err
        err = parts_scan_gate(tmp, root)
        if err:
            return err
        proc = subprocess.run([sys.executable, str(tmp / "scripts" / "build-pages.py"), "--check"],
                              cwd=tmp, capture_output=True, text=True, timeout=300)
        if proc.returncode != 0:
            tail = (proc.stdout + proc.stderr).strip().splitlines()
            named = ", ".join(overlay + drop)
            return ("the prospective remote tree does not build: file(s) that would not "
                    "reach " + branch + " in their local form: " + named
                    + " - the derived artifacts were built from the local tree. "
                    "Push them too, or revert them locally. build-pages --check said: "
                    + (tail[-1] if tail else "(no output)"))
        return None
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def receipts_gate(prospective_root, instrument_root, remote, local, resolved):
    """CURRENT mutation receipts must cover every check/judge file
    this push changes (class N1; scripts/check-receipts.py owns the
    scope and the coverage rule). The checking logic is loaded from
    the LOCAL tree - the measuring instrument, exempt from the
    prospective overlay like build-pages.py - while the receipts
    file and the pinned files are read from the PROSPECTIVE tree,
    so a receipt that would not land with this push cannot certify
    it. Returns an error string or None."""
    script = instrument_root / "scripts" / "check-receipts.py"
    if not script.is_file():
        print("RECEIPTS GATE SKIPPED: scripts/check-receipts.py is not in "
              "this tree (it predates the gate)")
        return None
    spec = importlib.util.spec_from_file_location("snow_check_receipts", script)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    changed = [p for p in resolved if remote.get(p) != local.get(p)]
    triggers = mod.trigger_paths(changed)
    if not triggers:
        return None
    missing, err = mod.uncovered(prospective_root, triggers)
    if err:
        return "the mutation-receipt gate cannot run: " + err
    if missing:
        return mod.refusal_text(missing)
    print(f"RECEIPTS GATE: {len(triggers)} changed check/judge path(s) covered "
          "by current mutation receipts")
    return None


