// In-repo copy of the basemap style generator (Beta 1.94, audit F-02):
// run from scripts/ (cd scripts && node genstyles.mjs) with the
// @protomaps/basemaps package installed; it writes ../parts/pmstyles.js,
// after which scripts/assemble.py + scripts/build-pages.py rebuild the page.
// Generates parts/pmstyles.js - the app's two basemaps (Beta 1.33, Andrew's pick:
// Protomaps, one map in two flavours). The tile endpoint is pulled LIVE from CARTO's
// dark-matter style at generation time, so a CARTO tile-version rotation is picked up
// by regenerating, never by hand-editing this output. DO NOT hand-edit pmstyles.js.
import fs from 'fs';
import { layers, namedFlavor } from '@protomaps/basemaps';

const dm = await (await fetch('https://basemaps.cartocdn.com/gl/dark-matter-gl-style/style.json')).json();
const tiles = dm.sources.protomaps.tiles;
if (!Array.isArray(tiles) || !tiles[0].includes('tiles.basemaps.cartocdn.com')) throw new Error('unexpected dark-matter source: ' + JSON.stringify(dm.sources).slice(0, 200));

function style(flavor) {
  return {
    version: 8,
    name: 'protomaps-' + flavor,
    glyphs: 'https://protomaps.github.io/basemaps-assets/fonts/{fontstack}/{range}.pbf',
    sprite: 'https://protomaps.github.io/basemaps-assets/sprites/v4/' + flavor,
    sources: { protomaps: { type: 'vector', tiles, minzoom: 0, maxzoom: 15, attribution: '© OpenStreetMap contributors © CARTO' } },
    layers: layers('protomaps', namedFlavor(flavor), { lang: 'en' })
  };
}
function add3d(s) { // Beta 1.90 (Andrew): 3D buildings - the flat footprint fill hands over to a fill-extrusion twin parked just below the labels. The route tiles carry footprints but no heights (checked on his streets: 492 buildings, none with a height), so the height is an estimate - a standard two-storey 7 m, using a real recorded height where the tile happens to carry one. Top-down is unchanged: the extrusion's top face is the old fill (same colour, same 0.5 blend, height 0 below z15, rising to full by z15.3).
  const flat = s.layers.find(l => l.id === 'buildings');
  flat.paint['fill-opacity'] = 0;
  const i = s.layers.findIndex(l => l.type === 'symbol');
  s.layers.splice(i, 0, { id: 'buildings-3d', type: 'fill-extrusion', source: 'protomaps', 'source-layer': 'buildings', minzoom: 14, filter: ['in', 'kind', 'building', 'building_part'], paint: { 'fill-extrusion-color': flat.paint['fill-color'], 'fill-extrusion-opacity': 0.5, 'fill-extrusion-height': ['interpolate', ['linear'], ['zoom'], 15, 0, 15.3, ['coalesce', ['get', 'height'], 7]], 'fill-extrusion-base': 0 } });
  return s;
}
const day = add3d(style('light')), night = add3d(style('dark'));
if (day.layers.length !== night.layers.length) throw new Error('flavour layer counts differ');
const out = '// GENERATED by scripts/genstyles.mjs (' + new Date().toISOString().slice(0, 10) + ', @protomaps/basemaps, tiles ' + tiles[0].split('/')[4] + ') - do not hand-edit; regenerate instead.\n' +
  '// Beta 1.33 (Andrew): BOTH basemaps are Protomaps - one map, two flavours - embedded in the page so a day/night switch is a local setStyle with nothing to fetch and nothing to break.\n' +
  'const PM_DAY = ' + JSON.stringify(day) + ';\n' +
  'const PM_NIGHT = ' + JSON.stringify(night) + ';\n';
fs.writeFileSync('../parts/pmstyles.js', out);
console.log('pmstyles.js written:', day.layers.length, 'layers per flavour, tiles:', tiles[0]);
