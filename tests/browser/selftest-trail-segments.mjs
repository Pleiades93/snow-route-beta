// Phase 2 (architecture C1) fixture proof for the shared trail segmenter.
// The segment-acceptance rule (break on gap > 300 s, jump > 1000 m, or a
// session marker between the points) is judging logic: it decides what
// trailKm counts, what drawTrail draws and how buildGpx splits tracks.
// Per the test-change gate (docs/TESTING.md) it ships with fixtures proven
// in plain Node BEFORE CI: the three app functions are extracted verbatim
// from the parts (balanced-brace extraction - a failed extraction fails
// this test loudly) and run against the golden outputs captured from the
// PRE-REFACTOR implementations (fixtures/trail-golden.json, generated by
// driving Beta 1.98's buildGpx/trailKm over the same synthetic trails).
// Any behavioural drift - a moved constant, a reordered walk, a changed
// boundary - fails here in under a second.
import { readFileSync } from 'node:fs';

const app1 = readFileSync(new URL('../../parts/app1.js', import.meta.url), 'utf8');
const app3 = readFileSync(new URL('../../parts/app3.js', import.meta.url), 'utf8');
const app4 = readFileSync(new URL('../../parts/app4.js', import.meta.url), 'utf8');
const golden = JSON.parse(readFileSync(new URL('./fixtures/trail-golden.json', import.meta.url), 'utf8'));

function extract(src, sig) {
  const i = src.indexOf(sig);
  if (i < 0) throw new Error('extraction failed: ' + sig + ' not found');
  let depth = 0, j = src.indexOf('{', i);
  for (; j < src.length; j++) { if (src[j] === '{') depth++; else if (src[j] === '}') { depth--; if (!depth) return src.slice(i, j + 1); } }
  throw new Error('extraction failed: unbalanced ' + sig);
}
const mline = app1.match(/const MLAT = [0-9]+, MLNG = [0-9]+/)[0];
const factory = new Function(`
  ${mline};
  let trail = [], trailSessions = [];
  ${extract(app1, 'function distM(')}
  ${extract(app1, 'function trailSegments(')}
  ${extract(app3, 'function trailKm(')}
  ${extract(app4, 'function buildGpx(')}
  return { trailSegments, trailKm, buildGpx, set: (t, s) => { trail = t; trailSessions = s; } };
`);
const A = factory();

const TRAILS = {
  g1_continuous: { pts: [[43.82, -79.57, 1000], [43.82045, -79.57, 1010], [43.8209, -79.57, 1020], [43.82135, -79.57, 1030], [43.8218, -79.57, 1040], [43.82225, -79.57, 1050]], sess: [] },
  g2_timegaps: { pts: [[43.82, -79.57, 1000], [43.8201, -79.57, 1300], [43.8202, -79.57, 1601], [43.8203, -79.57, 1610]], sess: [] },
  g3_jumps: { pts: [[43.82, -79.57, 1000], [43.82 + 999 / 111320, -79.57, 1010], [43.82 + 999 / 111320 + 1001 / 111320, -79.57, 1020], [43.82 + 999 / 111320 + 1001 / 111320 + 0.01, -79.57, 1030]], sess: [] },
  g4_markers: { pts: [[43.82, -79.57, 1000], [43.8201, -79.57, 1010], [43.8202, -79.57, 1020], [43.8203, -79.57, 1030], [43.8204, -79.57, 1040]], sess: [1005, 1020, 1030, 1035, 1037, 9999] },
  g5_backward: { pts: [[43.82, -79.57, 1000], [43.8201, -79.57, 1050], [43.8202, -79.57, 1020], [43.8203, -79.57, 1080], [43.8204, -79.57, 1090]], sess: [1010, 1040, 1070] },
  g6_empty: { pts: [], sess: [] },
  g7_single: { pts: [[43.82, -79.57, 1000]], sess: [1000] },
  g8_marker_and_gap: { pts: [[43.82, -79.57, 1000], [43.8201, -79.57, 1010], [43.8202, -79.57, 2000]], sess: [1015] }
};
let fails = 0;
const tss = segs => segs.map(s => s.map(p => p[2]));
for (const [name, t] of Object.entries(TRAILS)) {
  A.set(t.pts, t.sess);
  const g = golden[name];
  if (!g) { console.log('FAIL', name, 'no golden entry'); fails++; continue; }
  const gpx = A.buildGpx(), km0 = A.trailKm(0), kmMid = A.trailKm(1015500), kmFloor = A.trailKm(1020999);
  if (gpx !== g.gpx) { console.log('FAIL', name, 'GPX differs from the pre-refactor golden'); fails++; }
  if (km0 !== g.km0 || kmMid !== g.kmMid || kmFloor !== g.kmFloor) { console.log('FAIL', name, 'trailKm differs', { km0, kmMid, kmFloor }, 'golden', { km0: g.km0, kmMid: g.kmMid, kmFloor: g.kmFloor }); fails++; }
}
// Segment structure pinned directly (grouping, not just its GPX shadow):
const segExpect = [
  ['g2 boundary: 300 s holds, 301 s breaks', 'g2_timegaps', [[1000, 1300], [1601, 1610]]],
  ['g4 markers: between / at-end / at-start / doubled / beyond', 'g4_markers', [[1000], [1010], [1020], [1030], [1040]]],
  ['g5 backward step re-seeks markers', 'g5_backward', [[1000], [1050, 1020], [1080, 1090]]]
];
for (const [label, key, want] of segExpect) {
  const t = TRAILS[key];
  const got = tss(A.trailSegments(t.pts, t.sess));
  if (JSON.stringify(got) !== JSON.stringify(want)) { console.log('FAIL segment structure:', label, 'got', JSON.stringify(got), 'want', JSON.stringify(want)); fails++; }
}
if (fails) { console.log('selftest-trail-segments: ' + fails + ' FAILURE(S)'); process.exit(1); }
console.log('selftest-trail-segments: all fixtures hold (8 golden trails x GPX + 3 trailKm windows, 3 segment structures)');
